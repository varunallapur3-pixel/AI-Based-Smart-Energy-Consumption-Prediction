export function generateHardwareId(): string {
  const randHex = Math.floor(Math.random() * 0xfffff)
    .toString(16)
    .toUpperCase()
    .padStart(5, '0');
  return `VIRT_NODE_${randHex}`;
}

export function generateHmacSecret(): string {
  const chars = '0123456789abcdef';
  let token = '';
  for (let i = 0; i < 24; i++) {
    token += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  // Explicitly prefixed as a synthetic simulation secret, never production credentials
  return `vtx_sim_sec_${token}`;
}

export function generateFirmwareConfigHeader(input: ProvisionFormInput): string {
  const timestamp = new Date().toISOString();
  return `/**
 * ============================================================================
 * VOLTIX IoT Node Provisioning Header (SIMULATION / DEMO BUILD)
 * Auto-generated by VOLTIX Gateway Management Console
 * Generated: ${timestamp}
 *
 * IMPORTANT SECURITY NOTICE:
 * - This configuration is generated for simulated / virtual node emulation only.
 * - It does NOT contain real production secrets, API credentials, or private keys.
 * - Ephemeral keys and tokens generated here are strictly synthetic.
 * - Do NOT compile or flash this header onto physical grid-connected hardware.
 * ============================================================================
 */
#ifndef VOLTIX_NODE_CONFIG_H
#define VOLTIX_NODE_CONFIG_H

#define VOLTIX_BUILD_PROFILE      "SIMULATION_DEMO"
#define VOLTIX_IS_SIMULATED       1
#define VOLTIX_FIRMWARE_VER       "2.1.4_STABLE"
#define VOLTIX_NODE_ID            "${input.hwId}"
#define VOLTIX_NODE_NAME          "${input.friendlyName}"
#define VOLTIX_SIM_SECURITY_KEY   "${input.securityToken}"
#define VOLTIX_SENSOR_TYPE        "${input.sensorType}"
#define VOLTIX_PHASE_ASSIGNMENT   "${input.phase}"
#define VOLTIX_LOCATION_TAG       "${input.location}"
#define VOLTIX_HEARTBEAT_SEC      ${input.heartbeatSec}
#define VOLTIX_DEMO_FALLBACK      ${input.fallbackToDemo ? 1 : 0}

// Simulated Local Transport (Development Only)
#define VOLTIX_MQTT_BROKER        "localhost"
#define VOLTIX_MQTT_PORT          1883
#define VOLTIX_WS_ENDPOINT        "/api/telemetry/ws"

#endif // VOLTIX_NODE_CONFIG_H
`;
}

export function downloadConfigFile(input: ProvisionFormInput) {
  const content = generateFirmwareConfigHeader(input);
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${input.hwId}_config.h`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function exportFleetManifestJson(devices: DeviceNode[]) {
  const manifest = {
    schema_version: '2.4.0',
    export_timestamp: new Date().toISOString(),
    fleet_count: devices.length,
    active_cluster: 'ESP32_CLUSTER_01',
    devices: devices.map((d) => ({
      id: d.id,
      name: d.name,
      mac: d.mac,
      ip: d.ip,
      hardware: d.hwModel,
      sensor_interface: d.sensorInterface,
      location: d.location,
      phase: d.phase,
      status: d.status,
      is_simulated: d.isSimulated,
      firmware: d.firmwareVersion,
    })),
  };

  const blob = new Blob([JSON.stringify(manifest, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `voltix_fleet_manifest_${Date.now()}.json`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

